"""Tests for the full merge workflow: add IDs → parse results → merge.

These tests verify that classification results are correctly merged back with
the original input CSV, covering both auto-generated and custom ID columns.
"""

import json
from pathlib import Path

import polars as pl

from classify.core.csv_processor import ID_COLUMN, add_ids_to_csv, merge_results
from classify.core.results import parse_batch_results


def make_batch_response(custom_id: str, classification: dict) -> dict:
    """Create a mock batch API response record."""
    return {
        "custom_id": custom_id,
        "result": {
            "type": "succeeded",
            "message": {
                "content": [{"type": "text", "text": json.dumps(classification)}]
            },
        },
    }


def write_response_jsonl(path: Path, records: list[dict]) -> None:
    """Write batch response records as JSONL."""
    with open(path, "w") as f:
        for record in records:
            f.write(json.dumps(record) + "\n")


class TestMergeWithAutoGeneratedIds:
    """Tests for merging when using auto-generated sequential IDs."""

    def test_merge_with_sequential_ids(self, tmp_path: Path) -> None:
        """Full workflow: auto IDs → parse results → merge."""
        # 1. Create input CSV
        csv_path = tmp_path / "input.csv"
        csv_path.write_text("name,email\nAlice,alice@test.com\nBob,bob@test.com\n")

        # 2. Add sequential IDs
        input_with_ids = tmp_path / "input_with_ids.csv"
        add_ids_to_csv(csv_path, input_with_ids, id_column=None)

        # Verify IDs were added
        df = pl.read_csv(input_with_ids)
        assert ID_COLUMN in df.columns
        assert df[ID_COLUMN].to_list() == [1, 2]

        # 3. Simulate batch response (row IDs as strings from API)
        responses = [
            make_batch_response("row_1", {"category": "A", "score": 5}),
            make_batch_response("row_2", {"category": "B", "score": 3}),
        ]
        response_path = tmp_path / "batch_response.jsonl"
        write_response_jsonl(response_path, responses)

        # 4. Parse results
        results_path = tmp_path / "results.csv"
        errors_path = tmp_path / "errors.json"
        success, errors = parse_batch_results(response_path, results_path, errors_path)
        assert success == 2
        assert errors == 0

        # 5. Merge
        output_path = tmp_path / "output.csv"
        merge_results(input_with_ids, results_path, output_path)

        # 6. Verify merged output
        merged = pl.read_csv(output_path)
        assert len(merged) == 2
        assert "name" in merged.columns
        assert "email" in merged.columns
        assert "category" in merged.columns
        assert "score" in merged.columns
        assert merged["name"].to_list() == ["Alice", "Bob"]
        assert merged["category"].to_list() == ["A", "B"]
        assert merged["score"].to_list() == [5, 3]

    def test_merge_preserves_all_input_rows_on_partial_results(
        self, tmp_path: Path
    ) -> None:
        """Left join ensures input rows without results get null values."""
        csv_path = tmp_path / "input.csv"
        csv_path.write_text("name\nAlice\nBob\nCharlie\n")

        input_with_ids = tmp_path / "input_with_ids.csv"
        add_ids_to_csv(csv_path, input_with_ids, id_column=None)

        # Only return results for rows 1 and 3 (skip row 2)
        responses = [
            make_batch_response("row_1", {"category": "A"}),
            make_batch_response("row_3", {"category": "C"}),
        ]
        response_path = tmp_path / "batch_response.jsonl"
        write_response_jsonl(response_path, responses)

        results_path = tmp_path / "results.csv"
        errors_path = tmp_path / "errors.json"
        parse_batch_results(response_path, results_path, errors_path)

        output_path = tmp_path / "output.csv"
        merge_results(input_with_ids, results_path, output_path)

        merged = pl.read_csv(output_path)
        assert len(merged) == 3
        assert merged["name"].to_list() == ["Alice", "Bob", "Charlie"]
        # Bob's category should be null
        assert merged["category"][0] == "A"
        assert merged["category"][1] is None
        assert merged["category"][2] == "C"


