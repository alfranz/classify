class TestMetadataPathConsistency:
    """Tests that verify metadata paths are correct after batch directory rename."""

    def test_metadata_paths_updated_after_rename(self, tmp_path: Path) -> None:
        """Simulate the batch directory rename and verify paths are updated.

        This tests the core bug: after files move from temp dir to actual dir,
        metadata.input_csv_path must point to the new location.
        """
        from classify.core.models import BatchMetadata, BatchStatus
        from datetime import datetime

        # Simulate creating temp batch dir with metadata
        temp_dir = tmp_path / ".classify" / "batch_temp_example"
        temp_dir.mkdir(parents=True)

        csv_path = tmp_path / "input.csv"
        csv_path.write_text("name\nAlice\nBob\n")

        input_with_ids = temp_dir / "input_with_ids.csv"
        add_ids_to_csv(csv_path, input_with_ids, id_column=None)

        # Create metadata pointing to temp dir (as the old code would)
        metadata = BatchMetadata(
            batch_id="temp_example",
            status=BatchStatus.PENDING,
            created_at=datetime.now(),
            updated_at=datetime.now(),
            total_requests=2,
            config_path=str(temp_dir / "config.yaml"),
            input_csv_path=str(temp_dir / "input_with_ids.csv"),
            batch_request_path=str(temp_dir / "batch_request.jsonl"),
            errors_path=str(temp_dir / "errors.json"),
        )

        # Simulate the rename to actual batch dir
        actual_dir = tmp_path / ".classify" / "batch_msgbatch_abc123"
        actual_dir.mkdir(parents=True)
        input_with_ids.rename(actual_dir / "input_with_ids.csv")

        # BUG: if we don't update paths, merge will fail
        # because metadata.input_csv_path still points to temp_dir
        assert not Path(metadata.input_csv_path).exists()

        # FIX: update paths to actual dir
        metadata.input_csv_path = str(actual_dir / "input_with_ids.csv")
        assert Path(metadata.input_csv_path).exists()

        # Now verify merge works with the corrected path
        responses = [
            make_batch_response("row_1", {"label": "X"}),
            make_batch_response("row_2", {"label": "Y"}),
        ]
        response_path = tmp_path / "batch_response.jsonl"
        write_response_jsonl(response_path, responses)

        results_path = tmp_path / "results.csv"
        errors_path = tmp_path / "errors.json"
        parse_batch_results(response_path, results_path, errors_path)

        output_path = tmp_path / "output.csv"
        merge_results(Path(metadata.input_csv_path), results_path, output_path)

        merged = pl.read_csv(output_path)
        assert len(merged) == 2
        assert merged["name"].to_list() == ["Alice", "Bob"]
        assert merged["label"].to_list() == ["X", "Y"]
